package cards.ironeye;

import basemod.abstracts.CustomCard;
import com.megacrit.cardcrawl.actions.AbstractGameAction;
import com.megacrit.cardcrawl.actions.common.ApplyPowerAction;
import com.megacrit.cardcrawl.actions.common.DamageAction;
import com.megacrit.cardcrawl.cards.AbstractCard;
import com.megacrit.cardcrawl.cards.DamageInfo;
import com.megacrit.cardcrawl.characters.AbstractPlayer;
import com.megacrit.cardcrawl.core.CardCrawlGame;
import com.megacrit.cardcrawl.localization.CardStrings;
import com.megacrit.cardcrawl.monsters.AbstractMonster;
import patches.AbstractCardEnum;
import powers.DeathblightPower;

import java.util.ArrayList;

public class AncientDeath extends CustomCard {
    public static final String ID = "AncientDeath";
    private static final CardStrings STRINGS = CardCrawlGame.languagePack.getCardStrings(ID);

    public AncientDeath() {
        super(ID, STRINGS.NAME, "img/cards/ironeye/AncientDeath.png", 2, STRINGS.DESCRIPTION,
                CardType.ATTACK, AbstractCardEnum.Ironeye_COLOR, CardRarity.RARE, CardTarget.ENEMY);
        baseDamage = 10;
        baseMagicNumber = magicNumber = 1;
    }

    @Override
    public void use(AbstractPlayer p, AbstractMonster m) {
        addToBot(new AbstractGameAction() {
            @Override
            public void update() {
                if (isDone) return;
                isDone = true;
                // Exhaust the current hand once, not cards generated by exhaust callbacks.
                for (AbstractCard card : new ArrayList<>(p.hand.group)) {
                    if (p.hand.contains(card)) {
                        p.hand.moveToExhaustPile(card);
                    }
                }
                CardCrawlGame.dungeon.checkForPactAchievement();
            }
        });
        addToBot(new DamageAction(m, new DamageInfo(p, damage, damageTypeForTurn),
                AbstractGameAction.AttackEffect.SLASH_HEAVY));
        addToBot(new ApplyPowerAction(m, p, new DeathblightPower(m, magicNumber), magicNumber));
    }

    @Override
    public void upgrade() {
        if (!upgraded) {
            upgradeName();
            upgradeDamage(8);
        }
    }

    @Override
    public AbstractCard makeCopy() {
        return new AncientDeath();
    }
}
